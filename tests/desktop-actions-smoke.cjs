// Run against an isolated Tauri/WebView2 profile with CDP enabled.
/* global window, document, innerWidth */
const assert = require('node:assert/strict'), fs = require('node:fs/promises'), path = require('node:path')
const out = process.env.GITVIZ_DESKTOP_TEST_ROOT
if (!out || !path.isAbsolute(out)) throw new Error('GITVIZ_DESKTOP_TEST_ROOT must be an absolute scratch directory')
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core')
process.env.GITVIZ_LARGE_TEST_ROOT = out
const { largeRepo } = require('./helpers/large-repo.cjs')
;(async () => {
  const f = await largeRepo(25), initial = await f.git.head()
  const browser = await chromium.connectOverCDP(process.env.GITVIZ_CDP_URL || 'http://127.0.0.1:9248')
  const p = browser.contexts()[0].pages()[0], btn = name => p.getByRole('button', { name, exact: true })
  const errors = []; p.on('pageerror', e => errors.push(e.message))
  p.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const dialog = p.getByRole('dialog'), panel = p.getByRole('region', { name: '存档操作' })
  const drop = async root => {
    await p.evaluate(root => window.__TAURI_INTERNALS__.invoke('plugin:event|emit', { event: 'tauri://drag-drop', payload: { paths: [root], position: { x: 200, y: 200 } } }), root)
    await p.waitForFunction(expected => document.querySelector('.source-repo-path')?.textContent.replaceAll('\\', '/') === expected.replaceAll('\\', '/'), root)
    await p.locator('.save-node').first().waitFor()
    assert.equal(await p.locator('.desktop-actions').count(), 1)
  }
  const pickOldest = async () => {
    await p.locator('.map-viewport').press('End')
    await panel.getByText(f.first.slice(0, 7), { exact: true }).waitFor()
  }
  await drop(f.root); await pickOldest()
  const branchName = '试验/从旧版本继续'
  await btn('建分支').click(); await p.getByLabel('新分支名称').fill(branchName)
  await btn('预览分支创建').click(); await dialog.waitFor()
  assert.match(await dialog.innerText(), /原目录不变/); assert.match(await dialog.innerText(), /试验\/从旧版本继续/)
  assert.equal(await f.git.head(), initial)
  await p.keyboard.press('Escape')
  await assert.rejects(f.git.command(['show-ref', '--verify', `refs/heads/${branchName}`]))
  assert.equal(await p.getByLabel('新分支名称').inputValue(), branchName)
  await btn('预览分支创建').click(); await btn('确认创建分支').click()
  await panel.getByText('已创建分支', { exact: false }).waitFor()
  assert.equal(await f.git.head(), initial)
  assert.equal((await f.git.command(['rev-parse', branchName])).trim(), f.first)
  await p.locator('.branch-chip').filter({ hasText: branchName }).waitFor()

  // Change the repository after preview. The ticket must fail, then a refreshed
  // session must allow a fresh attempt without closing the repository.
  await btn('建分支').click(); await p.getByLabel('新分支名称').fill('retry-after-external-change')
  await btn('预览分支创建').click(); await dialog.waitFor()
  await f.git.command(['-c', 'core.hooksPath=', 'commit', '--allow-empty', '-m', 'external change'])
  const external = await f.git.head()
  await btn('确认创建分支').click(); await panel.getByRole('alert').waitFor()
  assert.match(await panel.getByRole('alert').innerText(), /历史已变化/)
  await assert.rejects(f.git.command(['show-ref', '--verify', 'refs/heads/retry-after-external-change']))
  await p.waitForFunction(id => document.querySelector('.desktop-history-position')?.textContent.includes(id), external.slice(0, 7))
  await btn('预览分支创建').click(); await btn('确认创建分支').click()
  await panel.getByText('已创建分支', { exact: false }).waitFor()
  assert.equal(await f.git.head(), external)

  // Cancelling restore leaves HEAD, index and files unchanged.
  await btn('恢复此存档').click(); await dialog.waitFor()
  await p.screenshot({ path: `${out}/actions-restore-confirm.png` })
  await btn('取消').click(); assert.equal(await f.git.head(), external)
  assert.equal(await fs.readFile(`${f.root}/counter.txt`, 'utf8'), 'save 25\n')
  await btn('恢复此存档').click(); await btn('备份并恢复').click()
  await panel.getByText('已恢复为新提交', { exact: false }).waitFor()
  const restored = await f.git.head()
  assert.notEqual(restored, external)
  assert.equal((await f.git.command(['rev-parse', 'HEAD^'])).trim(), external)
  assert.equal((await f.git.command(['rev-parse', 'HEAD^{tree}'])).trim(), (await f.git.command(['rev-parse', `${f.first}^{tree}`])).trim())
  assert.equal(await f.git.status(), '')
  const backup = await panel.locator('.desktop-action-result > code').innerText()
  assert.equal((await f.git.command(['rev-parse', backup])).trim(), external)
  await p.waitForFunction(id => document.querySelector('.desktop-history-position')?.textContent.includes(id), restored.slice(0, 7))
  await p.locator('.commit-detail .oid').filter({ hasText: restored }).waitFor()

  // Dirty original repository stays untouched while creating an independent worktree.
  await fs.writeFile(`${f.root}/counter.txt`, 'unsaved original\n')
  await btn('刷新历史').click()
  await p.getByText('有未提交修改，切换和恢复暂不可用。可以创建独立试验目录。', { exact: true }).waitFor()
  assert.equal(await btn('恢复此存档').isDisabled(), true)
  assert.equal(await p.locator('.branch-chip.main').isDisabled(), true)
  await pickOldest(); await btn('从这里试一版').click()
  await p.getByLabel('新分支名称').fill('trial-independent')
  await p.getByPlaceholder('输入绝对路径，或选择文件夹').fill(`${out}/试验 空格`)
  await btn('预览试验工作区').click(); await dialog.waitFor()
  assert.match(await dialog.innerText(), /试验 空格/)
  await btn('确认创建工作区').click(); await btn('在地图中打开试验工作区').waitFor()
  const worktree = await panel.locator('.desktop-action-result > code').innerText()
  assert.equal(await fs.readFile(`${f.root}/counter.txt`, 'utf8'), 'unsaved original\n')

  assert.equal(await f.git.head(), restored)
  assert.equal(await fs.readFile(`${worktree}/counter.txt`, 'utf8'), 'save 1\n')
  await p.screenshot({ path: `${out}/actions-worktree.png` })
  await btn('在地图中打开试验工作区').click()
  await p.waitForFunction(() => document.querySelector('.source-repo-path')?.textContent.includes('gitviz-'))
  await p.waitForFunction(() => document.querySelector('.desktop-history-position')?.textContent.includes('trial-independent'))
  await p.locator('.commit-detail .oid').filter({ hasText: f.first }).waitFor()
  assert.equal(await p.locator('.desktop-actions').count(), 1)
  assert.equal(await fs.readFile(`${f.root}/counter.txt`, 'utf8'), 'unsaved original\n')

  const bare = await fs.mkdtemp(`${out}/bare-`)
  await f.git.command(['init', '--bare', bare])
  await p.evaluate(root => window.__TAURI_INTERNALS__.invoke('plugin:event|emit', { event: 'tauri://drag-drop', payload: { paths: [root], position: { x: 200, y: 200 } } }), bare)
  await p.locator('.drop-error').filter({ hasText: '裸仓库' }).waitFor()
  await btn('刷新历史').click()
  await p.waitForFunction(() => document.querySelector('.desktop-history-position')?.textContent.includes('trial-independent'))
  assert.ok((await p.locator('.source-repo-path').innerText()).includes('gitviz-'))

  // External detached HEAD is reflected without silently treating main as current.
  await f.git.command(['restore', '--', 'counter.txt']); await f.git.command(['switch', '--detach', f.first])
  await drop(f.root)
  await p.waitForFunction(() => document.querySelector('.desktop-history-position')?.textContent.includes('游离 HEAD'))
  assert.equal(await btn('恢复此存档').isDisabled(), true)
  await p.locator('.branch-chip.main').click(); await btn('确认操作').click()
  await p.waitForFunction(() => document.querySelector('.desktop-history-position')?.textContent.includes('main'))
  assert.equal(await f.git.head(), restored)

  // A failing hook leaves recoverable state and a visible backup reference.
  await fs.writeFile(`${f.root}/counter.txt`, 'later\n'); await f.git.command(['add', '--', 'counter.txt']); await f.git.command(['commit', '-m', 'later version'])
  const later = await f.git.head(); await btn('刷新历史').click()
  await p.waitForFunction(id => document.querySelector('.desktop-history-position')?.textContent.includes(id), later.slice(0, 7))
  await pickOldest()
  await fs.writeFile(`${f.root}/.git/hooks/pre-commit`, '#!/bin/sh\necho fixture-ui-hook-rejected >&2\nexit 1\n')
  await btn('恢复此存档').click(); await btn('备份并恢复').click(); await panel.getByRole('alert').waitFor()
  const failure = await panel.getByRole('alert').innerText()
  assert.match(failure, /fixture-ui-hook-rejected/); assert.match(failure, /gitviz\/backup-/)
  assert.equal(await f.git.head(), later)
  assert.equal(await fs.readFile(`${f.root}/counter.txt`, 'utf8'), 'save 1\n')
  assert.notEqual(await f.git.status(), '')

  await p.setViewportSize({ width: 960, height: 600 })
  await btn('从这里试一版').click()
  await p.getByLabel('新分支名称').fill('long-name-'.repeat(12))
  await p.getByPlaceholder('输入绝对路径，或选择文件夹').fill(`${out}/试验 空格`)
  await p.screenshot({ path: `${out}/actions-960.png` })
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await btn('预览试验工作区').click(); await dialog.waitFor()
  const bounds = await dialog.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 960 && bounds.y >= 0 && bounds.y + bounds.height <= 600)
  await p.keyboard.press('Tab'); assert.equal(await dialog.evaluate(d => d.contains(document.activeElement)), true)
  await p.screenshot({ path: `${out}/actions-confirm-960.png` }); await p.keyboard.press('Escape')
  assert.deepEqual(errors, [])
  await fs.writeFile(`${out}/actions-ui-result.json`, JSON.stringify({ root: f.root, initial, external, restored, backup, worktree, branchCreationPreservesFiles: true, cancellationReadOnly: true, stalePreviewRejectedAndRetryWorks: true, restoreCreatesCommitAndBackup: true, dirtyWorktreeIndependent: true, opensLinkedWorktree: true, failedOpenKeepsPreviousRepository: true, detachedHeadCorrect: true, hookFailurePreservesData: true, emulatedViewport: { width: 960, height: 600 }, dialogBounds: bounds, errors }, null, 2))
  console.log('PASS desktop branch, restore, worktree, external HEAD, cancellation, failure and small viewport')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
