// Real Tauri/WebView2 flow. Only the isolated fixture receives Git writes.
/* global window, document, innerWidth */
const assert = require('node:assert/strict'), fs = require('node:fs/promises'), path = require('node:path')
const out = process.env.GITVIZ_DESKTOP_TEST_ROOT
if (!out || !path.isAbsolute(out)) throw new Error('GITVIZ_DESKTOP_TEST_ROOT must be an absolute scratch directory')
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core')
process.env.GITVIZ_LARGE_TEST_ROOT = out
const { largeRepo } = require('./helpers/large-repo.cjs')
;(async () => {
  const fixture = await largeRepo(25), original = await fixture.git.head(), root = fixture.root
  const browser = await chromium.connectOverCDP(process.env.GITVIZ_CDP_URL || 'http://127.0.0.1:9248')
  const p = browser.contexts()[0].pages()[0], button = name => p.getByRole('button', { name, exact: true })
  const history = p.locator('.operation-history'), dialog = p.getByRole('dialog'), errors = []
  p.on('pageerror', error => errors.push(error.message))
  const hook = path.join(root, '.git/hooks/pre-commit'), file = path.join(root, 'counter.txt')
  const failHook = () => fs.writeFile(hook, '#!/bin/sh\necho recovery-ui-hook-rejected >&2\nexit 1\n', { mode: 0o755 })
  const records = async () => {
    const folder = path.join(root, '.git/gitviz/operations')
    return Promise.all((await fs.readdir(folder)).filter(name => name.endsWith('.json')).map(async name => JSON.parse(await fs.readFile(path.join(folder, name), 'utf8'))))
  }
  const drop = async () => {
    await p.evaluate(root => window.__TAURI_INTERNALS__.invoke('plugin:event|emit', { event: 'tauri://drag-drop', payload: { paths: [root], position: { x: 200, y: 200 } } }), root)
    await p.waitForFunction(root => document.querySelector('.source-repo-path')?.textContent.replaceAll('\\', '/') === root.replaceAll('\\', '/'), root)
    await p.locator('.save-node').first().waitFor()
  }
  await p.setViewportSize({ width: 1280, height: 800 }); await drop()
  await p.locator('.map-viewport').press('End')
  await p.getByRole('region', { name: '存档操作' }).getByText(fixture.first.slice(0, 7), { exact: true }).waitFor()
  await failHook(); await button('恢复此存档').click(); await button('备份并恢复').click()
  await p.locator('.desktop-actions [role=alert]').filter({ hasText: 'recovery-ui-hook-rejected' }).waitFor()
  assert.equal(await fixture.git.head(), original)
  await history.locator(':scope > summary').click()
  const restore = history.locator('.operation-record').filter({ hasText: '恢复存档 · 未完成' })
  await restore.locator('summary').click()
  await restore.getByText('恢复前备份', { exact: true }).waitFor()
  const failed = (await records()).find(record => record.action === 'restore')
  assert.equal(failed.state, 'failed'); assert.equal(failed.attempts, 1)
  assert.equal((await fixture.git.command(['rev-parse', failed.backup])).trim(), original)

  // A cancelled recovery is read-only, including the index and attempt count.
  const indexBefore = await fs.readFile(path.join(root, '.git/index'))
  await button('检查并继续提交').click(); await dialog.waitFor()
  assert.match(await dialog.innerText(), /counter.txt/)
  await button('取消').click(); await dialog.waitFor({ state: 'hidden' })
  assert.deepEqual(await fs.readFile(path.join(root, '.git/index')), indexBefore)
  assert.equal((await records()).find(record => record.id === failed.id).attempts, 1)
  assert.match(await p.locator('.desktop-actions [role=alert]').innerText(), /recovery-ui-hook-rejected/)

  // A file changed after preview must never be silently included or overwritten.
  await button('检查并继续提交').click(); await dialog.waitFor()
  await fs.writeFile(file, 'external change after confirmation preview\n')
  await dialog.getByRole('button', { name: '检查并继续提交', exact: true }).click()
  await history.getByRole('alert').waitFor()
  assert.equal(await fixture.git.head(), original)
  assert.equal(await fs.readFile(file, 'utf8'), 'external change after confirmation preview\n')
  await fixture.git.command(['restore', '--worktree', '--', 'counter.txt'])
  await fs.unlink(hook)
  await button('检查并继续提交').click(); await dialog.waitFor()
  await dialog.getByRole('button', { name: '检查并继续提交', exact: true }).click()
  await history.locator('summary').filter({ hasText: '恢复存档 · 已完成' }).waitFor()
  const restored = await fixture.git.head()
  assert.equal((await fixture.git.command(['rev-parse', 'HEAD^'])).trim(), original)
  assert.equal((await fixture.git.command(['rev-parse', 'HEAD^{tree}'])).trim(), failed.checkpoint.tree)
  assert.equal(await fixture.git.status(), '')
  await p.waitForFunction(oid => document.querySelector('.desktop-history-position')?.textContent.includes(oid), restored.slice(0, 7))
  assert.equal(await p.locator('.desktop-actions [role=alert]').count(), 0)
  await history.locator(':scope > summary').scrollIntoViewIfNeeded()
  await p.screenshot({ path: path.join(out, 'recovery-desktop-complete.png') })

  // Reopening the repository reloads the persisted record through the real IPC.
  await button('Switch repo').click(); await drop()
  await history.locator(':scope > summary').click()
  await history.locator('summary').filter({ hasText: '恢复存档 · 已完成' }).waitFor()
  await p.locator('.map-viewport').press('End')
  await button('Edit').click(); await button('确认操作').click()
  await p.locator('.monaco-editor').waitFor({ timeout: 45000 })
  await p.locator('.monaco-editor').click(); await p.keyboard.press('Control+Home'); await p.keyboard.press('Control+A')
  await p.keyboard.insertText('recover this editor content\n')
  await failHook(); await button('Save & Commit').click(); await button('确认操作').click()
  await p.locator('.editor-panel .error').filter({ hasText: 'recovery-ui-hook-rejected' }).waitFor()
  assert.match((await p.locator('.monaco-editor .view-lines').innerText()).replaceAll('\u00a0', ' '), /recover this editor content/)
  const save = history.locator('.operation-record').filter({ hasText: '保存并提交 · 未完成' })
  await save.locator('summary').click()
  assert.equal(await save.getByRole('button', { name: '检查并继续提交' }).isDisabled(), true)
  await button('Cancel').click(); await button('放弃编辑').click()
  await p.locator('.editor-panel').waitFor({ state: 'hidden' })
  assert.equal(await fs.readFile(file, 'utf8'), 'recover this editor content\n')
  await fs.unlink(hook)
  await save.getByRole('button', { name: '检查并继续提交' }).click(); await dialog.waitFor()
  await p.setViewportSize({ width: 960, height: 600 })
  const bounds = await dialog.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 960 && bounds.y >= 0 && bounds.y + bounds.height <= 600)
  await p.keyboard.press('Tab'); assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true)
  await p.screenshot({ path: path.join(out, 'recovery-desktop-confirm-960.png') })
  await dialog.getByRole('button', { name: '检查并继续提交', exact: true }).click()
  await history.locator('summary').filter({ hasText: '保存并提交 · 已完成' }).waitFor()
  assert.equal(await fixture.git.status(), '')
  assert.equal((await fixture.git.command(['rev-parse', 'HEAD^'])).trim(), fixture.first)
  assert.equal(await fs.readFile(file, 'utf8'), 'recover this editor content\n')
  assert.match(await fixture.git.command(['log', '-1', '--format=%an <%ae>']), /Gitviz Test Fixture <fixture@example.invalid>/)
  await p.waitForFunction(oid => document.querySelector('.desktop-history-position')?.textContent.includes(oid), (await fixture.git.head()).slice(0, 7))
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  await fs.writeFile(path.join(out, 'recovery-desktop-result.json'), JSON.stringify({ root, original, restored, cancellationReadOnly: true, changedFilesAfterPreviewRejected: true, restoreTreeAndBackupPreserved: true, recoveredActionClearsStaleWarning: true, recordsSurviveReopen: true, editorBufferPreserved: true, recoveryDisabledWhileEditing: true, editorCommitResumed: true, userIdentityPreserved: true, dialogBounds: bounds, errors }, null, 2))
  console.log('PASS desktop recovery, cancellation, external changes, persistence, editor preservation and narrow confirmation')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
